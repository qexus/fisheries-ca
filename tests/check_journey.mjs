import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('public/index.html','utf8');
const app=fs.readFileSync('public/app.js','utf8');
const guard=fs.readFileSync('public/backup-guard.js','utf8');
assert(html.includes('data-qj-view="journey"'),'Candidate route missing from navigation');
assert(html.includes('https://qexus.github.io/shared/candidate-journey.css'),'Candidate styles missing');
const script=html.indexOf('src="https://qexus.github.io/shared/candidate-journey.js"');
const router=html.indexOf('src="https://qexus.github.io/shared/fisheries-router.js"');
assert(script>0&&router>script,'Candidate controller must load before router');
assert(app.includes('journey:window.qxCandidateJourney?.exportState?.()'),'JSON export must contain local candidate journey');
assert(app.includes('window.qxCandidateJourney.restoreState('),'JSON restoration must include candidate journey');
assert(app.includes('#main .qa-wrap,#main .qj-wrap'),'Async registry refresh must not erase active journey');
assert(guard.includes('validateSnapshot(snapshot.journey,country)'),'Backups must reject invalid route state before modifying saved data');
const window={qxCandidateJourney:{validateSnapshot:(journey,country)=>journey.version===1&&journey.country===country}};
vm.runInNewContext(guard,{window});
const no={app:'qexus-fishing',companies:[],vessels:[],statuses:{},lessons:{},checks:{}};
const ca={app:'qexus-fisheries-canada',data:{imported:[],completed:[],favorites:[],notes:{}}};
const fixture=ca;
const country='canada';
const valid={version:1,country};
assert(window.qxValidateBackup({...fixture,journey:valid},country),'Good journey backup accepted');
assert(window.qxValidateBackup(fixture,country),'Old backup without journey accepted');
assert.throws(()=>window.qxValidateBackup({...fixture,journey:{version:1,country:'other'}},country),'Wrong-country backup rejected');
window.qxCandidateJourney.validateSnapshot=()=>false;
assert.throws(()=>window.qxValidateBackup({...fixture,journey:valid},country),'Malformed journey rejected before mutation');
console.log('Passed: candidate menu, shared asset order, local-only JSON export, restoration and backup guard.');
